const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {gzipSync}=require('node:zlib');
const {execFileSync}=require('node:child_process');
test('shared stylesheet stays within the transfer budget and preserves runtime states',()=>{
  const css=fs.readFileSync('site.min.css');
  assert(css.length<60000,'CSS must stay under 60 KB');
  assert(gzipSync(css).length<14000,'Gzip CSS must stay under 14 KB');
  for(const token of ['mobile-nav-open','data-nav-ready','is-error','[hidden]',':focus-visible','schedule-next','session-capacity','count-feed-note','@media print'])assert(css.includes(token),'Missing runtime style: '+token);
});
test('public artifact includes all routes and excludes development files',()=>{
  execFileSync(process.execPath,['scripts/stage-site.cjs']);
  const names=fs.readdirSync('_site');
  for(const name of ['node_modules','tests','scripts','ops','work','outputs','README.md','package.json','styles.css'])assert(!names.includes(name),'Development file published: '+name);
  assert(!names.some(name=>name.endsWith('.png') && name!=='email-star-soccer-logo.png'),'Reference screenshots must not be published');
  for(const name of fs.readdirSync('.').filter(name=>name.endsWith('.html')))assert(names.includes(name),'Missing route: '+name);
  assert(fs.existsSync('_site/Star soccer/index.html'));
  assert(fs.existsSync('_site/site.min.css'));
  assert(fs.existsSync('_site/quick-forms.css'));
  assert(fs.existsSync('_site/session-counts.js'));
  assert(fs.existsSync('_site/weekly-signup.js'));
  assert(fs.existsSync('_site/weekly-signup-form.js'));
  assert(fs.existsSync('_site/campaign-source.js'),'Campaign attribution module must be in the deployed artifact');
  assert(fs.existsSync('_site/star-soccer-social.jpg'),'Search/share preview graphic must be in the deployed artifact');
  assert(fs.existsSync('_site/pass-calendar.js'));
  assert(fs.existsSync('_site/autumn-field-800.webp'));
  assert(fs.existsSync('_site/autumn-field-1600.webp'));
  for(const name of ['winter-field-800.webp','winter-field-1600.webp','winter-camps.js','camp-booking.js'])assert(fs.existsSync('_site/'+name),'Missing winter camp asset: '+name);
  assert(fs.statSync('_site/winter-field-800.webp').size<50000,'Mobile winter hero must stay under 50 KB');
  assert(fs.statSync('_site/winter-field-1600.webp').size<120000,'Desktop winter hero must stay under 120 KB');
  assert(fs.statSync('_site/autumn-field-800.webp').size<100000,'Mobile autumn photo must stay under 100 KB');
  assert(fs.statSync('_site/autumn-field-1600.webp').size<200000,'Desktop autumn photo must stay under 200 KB');
  assert(!names.some(name=>/^(autumn|winter)-training-/.test(name)),'Superseded generated artwork must not be published');
  for(const name of ['email-star-soccer-logo.png','email-autumn-field.jpg','email-winter-field.jpg'])assert(fs.existsSync('_site/'+name),'Missing email brand asset: '+name);
  assert(!fs.existsSync('_site/SESSION_COUNTS.md'));
  for(const font of ['manrope-normal','bebas-neue-normal','instrument-serif-normal','instrument-serif-italic'])assert(fs.existsSync('_site/fonts/'+font+'-latin.woff2'));
  for(const family of ['manrope','bebasneue','instrumentserif'])assert(fs.readFileSync('_site/fonts/'+family+'-OFL.txt','utf8').includes('SIL OPEN FONT LICENSE'));
  for(const name of ['home','contact','locations','approach'])for(const width of [800,1600])for(const format of ['avif','webp'])assert(fs.existsSync(`_site/site-photos/${name}-${width}.${format}`));
  for(const season of ['autumn','winter'])for(const width of [800,1600])assert(fs.existsSync(`_site/${season}-field-${width}.avif`));
});
